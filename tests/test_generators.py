class TestResolver:
    def test_fqdn_construction(self):
        cfg = load_config(FIXTURES / "full.toml")
        resolved = resolve(cfg)
        fqdns = {svc.fqdn for svc in resolved.services}
        assert "plex.home.example.com" in fqdns
        assert "photos.home.example.com" in fqdns

    def test_upstream_name(self):
        cfg = load_config(FIXTURES / "full.toml")
        resolved = resolve(cfg)
        names = {svc.upstream_name for svc in resolved.services}
        assert "proxysmith_plex" in names

    def test_use_ssl_true_for_auto(self):
        cfg = load_config(FIXTURES / "full.toml")
        resolved = resolve(cfg)
        assert all(svc.use_ssl for svc in resolved.services)

    def test_use_ssl_false_for_none(self):
        cfg = load_config(FIXTURES / "minimal.toml")
        resolved = resolve(cfg)
        assert all(not svc.use_ssl for svc in resolved.services)
