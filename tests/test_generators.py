"""Snapshot-style tests for all three config generators."""

from __future__ import annotations

from pathlib import Path

import pytest

from proxysmith.core.parser import load_config
from proxysmith.core.resolver import resolve
from proxysmith.generators import CaddyGenerator, NginxGenerator, TraefikGenerator

FIXTURES = Path(__file__).parent / "fixtures"


def _load(name: str):
    """Load and resolve a fixture config."""
    cfg = load_config(FIXTURES / name)
    return resolve(cfg)


# --------------------------------------------------------------------------- #
# Nginx                                                                        #
# --------------------------------------------------------------------------- #


class TestNginxGenerator:
    def test_generates_one_file(self):
        files = NginxGenerator().generate(_load("full.toml"))
        assert len(files) == 1
        assert files[0].filename == "nginx/proxysmith.conf"

    def test_contains_all_upstreams(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "upstream proxysmith_plex" in content
        assert "upstream proxysmith_immich" in content
        assert "upstream proxysmith_ollama" in content
        assert "upstream proxysmith_homepage" in content

    def test_server_names(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "server_name plex.home.example.com" in content
        assert "server_name photos.home.example.com" in content
        assert "server_name llm.home.example.com" in content
        assert "server_name dash.home.example.com" in content

    def test_ssl_redirect_present(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "return 301  https://$host$request_uri" in content

    def test_ssl_certificates_referenced(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "ssl_certificate" in content
        assert "letsencrypt" in content

    def test_websocket_upgrade(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        # plex has websocket=true
        assert 'proxy_set_header   Upgrade            $http_upgrade' in content

    def test_custom_headers_injected(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert 'X-Plex-Client-Identifier' in content

    def test_basic_auth_directive(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "auth_basic" in content
        assert "htpasswd/ollama" in content

    def test_rate_limit_zone(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "ollama_limit" in content

    def test_max_upload_size(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "client_max_body_size 10G" in content

    def test_no_ssl_when_mode_none(self):
        content = NginxGenerator().generate(_load("minimal.toml"))[0].content
        assert "ssl_certificate" not in content
        assert "return 301" not in content

    def test_generated_by_comment(self):
        content = NginxGenerator().generate(_load("minimal.toml"))[0].content
        assert "Generated by ProxySmith" in content

    def test_security_headers_present(self):
        content = NginxGenerator().generate(_load("full.toml"))[0].content
        assert "X-Frame-Options" in content
        assert "X-Content-Type-Options" in content
        assert "Strict-Transport-Security" in content

    def test_proxy_headers_chain(self):
        content = NginxGenerator().generate(_load("minimal.toml"))[0].content
        assert "X-Real-IP" in content
        assert "X-Forwarded-For" in content
        assert "X-Forwarded-Proto" in content


