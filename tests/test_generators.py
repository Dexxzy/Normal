class TestTraefikGenerator:
    def test_generates_two_files(self):
        files = TraefikGenerator().generate(_load("full.toml"))
        assert len(files) == 2
        filenames = {f.filename for f in files}
        assert "traefik/docker-compose.labels.yml" in filenames
        assert "traefik/file-provider.yml" in filenames

    def _docker(self, fixture="full.toml"):
        return next(
            f for f in TraefikGenerator().generate(_load(fixture))
            if "docker" in f.filename
        ).content

    def _file(self, fixture="full.toml"):
        return next(
            f for f in TraefikGenerator().generate(_load(fixture))
            if "file" in f.filename
        ).content

    def test_docker_labels_contain_fqdns(self):
        content = self._docker()
        assert "plex.home.example.com" in content
        assert "photos.home.example.com" in content

    def test_docker_labels_https_redirect(self):
        content = self._docker()
        assert "https-redirect" in content

    def test_docker_cert_resolver(self):
        content = self._docker()
        assert "letsencrypt" in content

    def test_file_provider_routers(self):
        content = self._file()
        assert "routers:" in content
        assert "services:" in content
        assert "middlewares:" in content

    def test_file_provider_fqdns(self):
        content = self._file()
        assert "plex.home.example.com" in content
        assert "photos.home.example.com" in content

    def test_file_provider_health_check(self):
        content = self._file()
        assert "healthCheck:" in content

    def test_rate_limit_in_docker(self):
        content = self._docker()
        assert "ratelimit" in content

    def test_basic_auth_in_docker(self):
        content = self._docker()
        assert "basicauth" in content

    def test_no_ssl_when_none(self):
        content = self._file("minimal.toml")
        assert "letsencrypt" not in content
        assert "websecure" not in content

    def test_generated_by_comment(self):
        assert "Generated by ProxySmith" in self._docker()
        assert "Generated by ProxySmith" in self._file()

    def test_security_headers_middleware(self):
        content = self._file()
        assert "securityheaders" in content
        assert "frameDeny" in content


